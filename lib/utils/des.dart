  /// 将字节数组展开为比特数组（高位在前）
  static List<int> _bits(List<int> bytes) {
    final out = <int>[];
    for (final b in bytes) {
      for (var i = 7; i >= 0; i--) {
        out.add((b >> i) & 1);
      }
    }
    return out;
  }

  /// 按置换表置换（表中下标从 1 开始）
  static List<int> _permute(List<int> bits, List<int> table) => [for (final i in table) bits[i - 1]];

  /// 生成 16 轮子密钥
  static List<List<int>> _createSubKeys(List<int> key) {
    final k = _permute(_bits(key), _pc1);
    var c = k.sublist(0, 28);
    var d = k.sublist(28);
    final subKeys = <List<int>>[];
    for (final s in _shifts) {
      c = [...c.sublist(s), ...c.sublist(0, s)];
      d = [...d.sublist(s), ...d.sublist(0, s)];
      subKeys.add(_permute([...c, ...d], _pc2));
    }
    return subKeys;
  }

  /// 加密 8 字节块
  Uint8List encryptBlock(List<int> block) {
    final bits = _permute(_bits(block), _ip);
    var l = bits.sublist(0, 32);
    var r = bits.sublist(32);
    for (var round = 0; round < 16; round++) {
      final er = _permute(r, _e);
      final x = [for (var i = 0; i < 48; i++) er[i] ^ _subKeys[round][i]];
      final sOut = <int>[];
      for (var j = 0; j < 8; j++) {
        final o = j * 6;
        final row = (x[o] << 1) | x[o + 5];
        final col = (x[o + 1] << 3) | (x[o + 2] << 2) | (x[o + 3] << 1) | x[o + 4];
        final v = _s[j][row * 16 + col];
        for (var b = 3; b >= 0; b--) {
          sOut.add((v >> b) & 1);
        }
      }
      final f = _permute(sOut, _p);
      final newR = [for (var i = 0; i < 32; i++) l[i] ^ f[i]];
      l = r;
      r = newR;
    }
    final out = _permute([...r, ...l], _fp);
    final bytes = Uint8List(8);
    for (var i = 0; i < 64; i++) {
      bytes[i ~/ 8] |= out[i] << (7 - (i % 8));
    }
    return bytes;
  }

  /// VNC 认证响应：密码截断/补零到 8 字节，每字节比特反转后作为 DES 密钥加密 16 字节挑战
  static Uint8List vncResponse(String password, List<int> challenge) {
    final key = Uint8List(8);
    final pw = password.codeUnits;
    for (var i = 0; i < 8 && i < pw.length; i++) {
      var b = pw[i] & 0xff;
      var r = 0;
      for (var j = 0; j < 8; j++) {
        r = (r << 1) | (b & 1);
        b >>= 1;
      }
      key[i] = r;
    }
    final des = Des(key);
    return Uint8List.fromList([
      ...des.encryptBlock(challenge.sublist(0, 8)),
      ...des.encryptBlock(challenge.sublist(8, 16)),
    ]);
  }
