/// Flutter 物理按键（USB HID 用法码）到 RDP 扫描码（PC/AT Set 1）的映射。
/// 扩展键用 0x100 标记，与 FreeRDP 的 RDP_SCANCODE 编码一致。
class RdpScancode {
  RdpScancode._();

  static const _ext = 0x100;

